/**
 * One consumer edit, and the one idea the whole install turns on.
 *
 * `present` is the same function the matching `wiring-*` check calls. It is shared by
 * being named once in `PRESENT` below and referenced from both places, and
 * `kit/test/wiring/install.test.ts` asserts the reference identity rather than the
 * behaviour. That identity is what makes "already installed" and "correctly installed"
 * one fact: `install` re-running is a no-op precisely when `verify-install` passes, and
 * there is no third state where one is satisfied and the other is not. Idempotency is
 * therefore not a property anyone maintains; it is the same function answering the same
 * question twice.
 *
 * `apply` returns `null` when its anchor is missing or is not unique. That is the honest
 * version of "abort only the edits whose own write target was hand-edited": there is no
 * managed-region convention anywhere in hex-web to detect against. An exhaustive grep
 * for `BEGIN MANAGED`, `@generated` and `AUTOGENERATED` across every `.ts .tsx .json
 * .yaml .mjs .css .sh` returns four whole-file "Code generated by the Encore client
 * generator. DO NOT EDIT." headers and nothing else, and zero of the files edited here
 * are generated: `routes.ts` is ninety-five lines of which about half is prose comment,
 * and `root.tsx`'s CSP doc comment alone is fifty-five lines. So "hand-edited" is not
 * knowable, and "I cannot find exactly one place to put this" is.
 *
 * `present` reads the file's text and the descriptor's path arithmetic and nothing else.
 * Assertions that need the filesystem or a process, such as whether a `paths` target
 * resolves to a real file or whether a declared submodule is actually committed, live in
 * `checks.ts`. Without that split, applying an edit could leave `present` false through
 * no fault of the applier, and `install` would report a refusal on a write that worked.
 */

