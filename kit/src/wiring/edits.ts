/** The three `paths` entries a consuming site needs, and what each must resolve to. */
export function tsconfigPathEntries(site: SiteDescriptor): [string, string][] {
	return [
		['@hex-pro/docs', `${site.mountFromSite}/src/index.ts`],
		['@hex-pro/docs/render', `${site.mountFromSite}/src/render/index.ts`],
		['@hex-pro/docs/contracts', `${site.mountFromSite}/src/contracts/index.ts`],
	];
}

/** The `prebuild` fragment. One spelling, so the predicate and the applier agree. */
export function prebuildFragment(site: SiteDescriptor): string {
	return (
		`${site.mountFromSite}/kit/bin/hexdocs prefetch --root ${site.repoFromSite} ` +
		`--site ${site.site} && node scripts/check-docs.mjs`
	);
}

function paths(text: string | null): Record<string, unknown> | null {
	if (text === null) return null;
	const parsed = parseJsonc(text);
	if (parsed === null || typeof parsed !== 'object') return null;
	const compilerOptions = (parsed as { compilerOptions?: unknown }).compilerOptions;
	if (compilerOptions === null || typeof compilerOptions !== 'object') return null;
	const table = (compilerOptions as { paths?: unknown }).paths;
	if (table === null || typeof table !== 'object') return null;
	return table as Record<string, unknown>;
}

function firstTarget(table: Record<string, unknown>, key: string): string | null {
	const value = table[key];
	if (!Array.isArray(value)) return null;
	const first = value[0];
	return typeof first === 'string' ? first : null;
}

/**
 * `compilerOptions.resolveJsonModule`, following `extends`.
 *
 * Following it is not optional, and this is the fact that would otherwise have made the
 * check fail both correctly configured consumers forever. Neither `apps/front` nor
 * `kcalc-web/front` sets `resolveJsonModule` in its own `tsconfig.json`; both extend
 * `config/tsconfig.front.json`, which sets it to `true`. hex-web's base config also
 * carries a `//` comment, so the extended file has to go through `stripComments` as well.
 *
 * The chain is followed for a bounded number of hops and only for a single string
 * `extends`. An array `extends` is TypeScript 5.0 and neither consumer uses one; where it
 * appears this returns `null`, which the check reports as "could not determine" rather
 * than as a failure.
 */
export function resolveJsonModuleOf(site: SiteDescriptor, file: string, depth = 0): boolean | null {
	if (depth > 8) return null;
	const text = site.files.read(file);
	if (text === null) return null;
	const parsed = parseJsonc(text);
	if (parsed === null || typeof parsed !== 'object') return null;
	const compilerOptions = (parsed as { compilerOptions?: unknown }).compilerOptions;
	if (compilerOptions !== null && typeof compilerOptions === 'object') {
		const value = (compilerOptions as { resolveJsonModule?: unknown }).resolveJsonModule;
		if (typeof value === 'boolean') return value;
	}
	const extend = (parsed as { extends?: unknown }).extends;
	if (typeof extend !== 'string') return null;
	return resolveJsonModuleOf(site, resolveFrom(dirnamePosix(file), extend), depth + 1);
}

function scripts(text: string | null): Record<string, unknown> | null {
	if (text === null) return null;
	const parsed = parseJsonc(text);
	if (parsed === null || typeof parsed !== 'object') return null;
	const table = (parsed as { scripts?: unknown }).scripts;
	if (table === null || typeof table !== 'object') return null;
	return table as Record<string, unknown>;
}

/**
 * Which scripts always run, and why only these two.
 *
 * npm and pnpm both fire `prebuild` before `build`, measured on npm 11 and pnpm 10, and
 * `hex-terraform/deploy/src/build.ts` runs one of the two on the deploy host before the
 * Docker build. `build` itself is the other always-run script and is kcalc's own idiom,
 * which inlines its pre-step as `node scripts/build-lastmod.mjs && react-router build`.
 * Anything else is a script somebody has to remember to type, which on a repository with
 * no CI is not a guard.
 */
const ALWAYS_RUN = ['prebuild', 'build'] as const;

export const PRESENT = {
	submodule(text: string | null, site: SiteDescriptor): boolean {
		return parseGitmodules(text ?? '').some((stanza) => stanza.path === site.mount);
	},

	/**
	 * Not enrolled, and any exclusion written the way the existing guard matches it.
	 *
	 * The question is enrolment, not the presence of a line. On hex-web the answer is
	 * "enrolled" until an exclusion is added, because line 3 is `- common/*`. On kcalc
	 * the answer is already "not enrolled": the file is an explicit literal include list
	 * with no glob and no `!` line anywhere, so an exclusion there would be inert
	 * decoration and a check that demanded one would fail a correctly wired repository
	 * forever.
	 *
	 * The quoting half is not cosmetic. `apps/front/scripts/check-tools.mjs:944` tests
	 * `workspace.includes('"!' + submodule.path + '"')`, a raw substring including the
	 * double quotes, so an unquoted YAML exclusion satisfies pnpm and fails that guard,
	 * which is a red row in a file this install never touched.
	 */
	workspaceExclusion(text: string | null, site: SiteDescriptor): boolean {
		if (text === null) return true;
		const entries = parseWorkspacePackages(text);
		let enrolled = false;
		let excluded = false;
		for (const entry of entries) {
			if (!workspaceMatches(entry, site.mount)) continue;
			if (entry.startsWith('!')) excluded = true;
			else enrolled = true;
		}
		if (excluded) return text.includes(`"!${site.mount}"`);
		return !enrolled;
	},

	tsconfigPaths(text: string | null, site: SiteDescriptor): boolean {
		const table = paths(text);
		if (table === null) return false;
		return tsconfigPathEntries(site).every(([key, target]) => firstTarget(table, key) === target);
	},

	tsconfigResolveJson(_text: string | null, site: SiteDescriptor): boolean {
		return resolveJsonModuleOf(site, joinPosix(site.site, 'tsconfig.json')) === true;
	},

	deployHashDirs(text: string | null, site: SiteDescriptor): boolean {
		// No deploy configuration at all means this repository does not deploy through
		// hex-terraform, so there is no hash to extend and nothing to do. The check
		// reports that state as a skip; here it is simply satisfied.
		if (text === null) return true;
		const parsed = parseJsonc(text);
		if (parsed === null || typeof parsed !== 'object') return false;
		if (site.projectType === null) return false;
		const hash = (parsed as { hash?: unknown }).hash;
		if (hash === null || typeof hash !== 'object') return false;
		const extra = (hash as { extra_dirs?: unknown }).extra_dirs;
		if (extra === null || typeof extra !== 'object') return false;
		const list = (extra as Record<string, unknown>)[site.projectType];
		return Array.isArray(list) && list.includes(site.mount);
	},

	prebuildHook(text: string | null, site: SiteDescriptor): boolean {
		const table = scripts(text);
		if (table === null) return false;
		return ALWAYS_RUN.some((name) => {
			const value = table[name];
			return (
				typeof value === 'string' &&
				value.includes('hexdocs prefetch') &&
				value.includes(`--site ${site.site}`) &&
				value.includes('check-docs.mjs')
			);
		});
	},

	/**
	 * The shim exists and spawns `verify-install` for this site.
	 *
	 * Not byte equality, and the reason is that byte equality would make this row fail on
	 * every consumer the moment the submodule is bumped to a kit whose generator produced
	 * one different character, which fails `prebuild`, which fails the deploy. A shim that
	 * an older kit wrote still works, because it holds no copy of what is checked: it
	 * spawns the CLI and renders whatever rows come back.
	 *
	 * The cost is stated rather than hidden: `install` will not refresh an existing shim,
	 * so a change to the generator reaches a consumer only when somebody deletes the file
	 * and runs `hexdocs install --write` again. That is the trade for not turning a
	 * submodule bump into a broken build.
	 */
	checkDocsShim(text: string | null, site: SiteDescriptor): boolean {
		if (text === null) return false;
		return text.includes('"verify-install"') && text.includes(JSON.stringify(site.site));
	},

	/**
	 * `app/lib/docs.ts` derives its three exports, however it has been reformatted.
	 *
	 * Not byte equality, unlike the shim, and the difference is deliberate: the header
	 * says "safe to edit" because a consumer with two documented projects and a reason to
	 * order them differently has somewhere to do it. So the predicate asks whether the
	 * module still derives from the three functions, which is what every needle in
	 * `checks.ts` then depends on.
	 */
	docsLib(text: string | null): boolean {
		if (text === null) return false;
		return (
			derives(text, 'docsLocalisedPathsFor(DOCS_SITES)') &&
			derives(text, 'docsRouteRows(DOCS_SITES)') &&
			derives(text, 'docsSitemapRows(DOCS_SITES)')
		);
	},

	siteConfig(_text: string | null, site: SiteDescriptor): boolean {
		return site.projects.length > 0;
	},

	mcpJson(text: string | null, site: SiteDescriptor): boolean {
		if (text === null) return false;
		const parsed = parseJsonc(text);
		if (parsed === null || typeof parsed !== 'object') return false;
		const servers = (parsed as { mcpServers?: unknown }).mcpServers;
		if (servers === null || typeof servers !== 'object') return false;
		const entry = (servers as Record<string, unknown>)['hexdocs'];
		if (entry === null || typeof entry !== 'object') return false;
		return (entry as { command?: unknown }).command === mcpServerEntry(site).command;
	},

	mcpSettings(_text: string | null, site: SiteDescriptor): boolean {
		return settingsSatisfied(site).ok;
	},

	gitignore(text: string | null): boolean {
		if (text === null) return false;
		const lines = text.split('\n').map((line) => line.trim());
		return GITIGNORE_ENTRIES.every((entry) => lines.includes(entry));
	},

	routes(text: string | null): boolean {
		if (text === null) return false;
		return derives(text, 'DOCS_ROUTES');
	},

	localisedPaths(text: string | null): boolean {
		if (text === null) return false;
		return derives(text, 'DOCS_PATHS');
	},

	sitemap(text: string | null): boolean {
		if (text === null) return false;
		return derives(text, 'DOCS_SITEMAP');
	},
} as const;

/**
 * Whether some settings file enables the server and grants the skills directory.
 *
 * Two ways to be enabled, and both are real. hex-web lists its three servers by name in
 * `enabledMcpjsonServers`; kcalc sets `enableAllProjectMcpServers: true` and lists one.
 * A check that only understood the first would fail a correctly wired kcalc forever,
 * which is the same shape of mistake as demanding a workspace exclusion there.
 *
 * Both files are read because neither is authoritative. `.claude/settings.json` does not
 * exist in hex-web at all, and its `.claude/settings.local.json` is ignored by the user's
 * global git ignore rather than by the repository, so it reaches no clone. The row says
 * which file carried the answer for exactly that reason.
 */
export function settingsSatisfied(site: SiteDescriptor): {
	ok: boolean;
	enabledBy: string | null;
	directoryIn: string | null;
	inspected: string[];
} {
	const candidates = ['.claude/settings.json', '.claude/settings.local.json'];
	const skills = `${site.mount}/.claude/skills`;
	let enabledBy: string | null = null;
	let directoryIn: string | null = null;
	const inspected: string[] = [];

	for (const file of candidates) {
		const text = site.files.read(file);
		if (text === null) continue;
		inspected.push(file);
		const parsed = parseJsonc(text);
		if (parsed === null || typeof parsed !== 'object') continue;
		const settings = parsed as Record<string, unknown>;
		const named = settings['enabledMcpjsonServers'];
		const all = settings['enableAllProjectMcpServers'];
		if (all === true || (Array.isArray(named) && named.includes('hexdocs'))) {
			enabledBy ??= file;
		}
		const permissions = settings['permissions'];
		if (permissions !== null && typeof permissions === 'object') {
			const directories = (permissions as { additionalDirectories?: unknown })
				.additionalDirectories;
			if (Array.isArray(directories) && directories.some((entry) => entry === skills)) {
				directoryIn ??= file;
			}
		}
	}

	return { ok: enabledBy !== null && directoryIn !== null, enabledBy, directoryIn, inspected };
}

