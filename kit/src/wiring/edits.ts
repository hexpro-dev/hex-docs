function withTrailingNewline(text: string): string {
	return text.endsWith('\n') ? text : `${text}\n`;
}

/** The bounds of the `packages:` list, as line indices into the split text. */
function packagesBlock(lines: readonly string[]): { from: number; to: number } | null {
	const from = lines.findIndex((line) => /^packages\s*:/.test(line));
	if (from === -1) return null;
	let to = lines.length;
	for (let i = from + 1; i < lines.length; i += 1) {
		const line = lines[i] as string;
		if (line.trim() === '') continue;
		if (/^\s/.test(line)) continue;
		if (line.trimStart().startsWith('#')) continue;
		to = i;
		break;
	}
	return { from, to };
}

const APPLY = {
	workspaceExclusion(text: string | null, site: SiteDescriptor): string | null {
		if (text === null) return null;
		const lines = text.split('\n');
		const block = packagesBlock(lines);
		if (block === null) return null;

		const wanted = `"!${site.mount}"`;
		let lastExclusion = -1;
		let enrolling = -1;
		for (let i = block.from + 1; i < block.to; i += 1) {
			const item = /^(\s*-\s*)(.+?)\s*$/.exec(lines[i] as string);
			if (item === null) continue;
			const value = (item[2] ?? '').replace(/^["']|["']$/g, '');
			if (value.startsWith('!')) lastExclusion = i;
			// An exclusion written without the quotes satisfies pnpm and fails
			// `check-tools.mjs`, so it is rewritten in place rather than duplicated.
			if (value === `!${site.mount}`) {
				lines[i] = `${item[1] ?? '  - '}${wanted}`;
				return lines.join('\n');
			}
			if (!value.startsWith('!') && workspaceMatches(value, site.mount)) enrolling = i;
		}

		const anchor = lastExclusion !== -1 ? lastExclusion : enrolling;
		if (anchor === -1) return null;
		const prefix = /^(\s*-\s*)/.exec(lines[anchor] as string)?.[1] ?? '  - ';
		lines.splice(anchor + 1, 0, `${prefix}${wanted}`);
		return lines.join('\n');
	},

	tsconfigPaths(text: string | null, site: SiteDescriptor): string | null {
		if (text === null) return null;
		const block = soleBlock(text, 'paths');
		if (block === null || block.kind !== 'object') return null;
		const table = paths(text);
		if (table === null) return null;
		const missing = tsconfigPathEntries(site).filter(
			([key, target]) => firstTarget(table, key) !== target,
		);
		if (missing.length === 0) return text;
		// A key that is present with the wrong target is left alone and reported rather
		// than rewritten. It means somebody pointed the specifier somewhere on purpose,
		// and a silent retarget is the one edit whose failure shows up as a wrong module
		// being compiled rather than as a build error.
		if (missing.some(([key]) => key in table)) return null;
		return insertIntoBlock(
			text,
			block,
			missing.map(([key, target]) => `${JSON.stringify(key)}: [${JSON.stringify(target)}]`),
		);
	},

	deployHashDirs(text: string | null, site: SiteDescriptor): string | null {
		if (text === null || site.projectType === null) return null;
		const extra = soleBlock(text, 'extra_dirs');
		if (extra === null || extra.kind !== 'object') return null;
		const list = soleBlockIn(text, extra, site.projectType);
		if (list !== null && list.kind === 'array') {
			return insertIntoBlock(text, list, [JSON.stringify(site.mount)]);
		}
		// kcalc's `extra_dirs` holds only a `worker` key, so the site's own key has to be
		// created rather than appended to. `?? []` at the reading end cannot tell the two
		// states apart, which is why they are separated here and in the check's message.
		return insertIntoBlock(text, extra, [
			`${JSON.stringify(site.projectType)}: [${JSON.stringify(site.mount)}]`,
		]);
	},

	/**
	 * Appends to this package's own `prebuild`, never to a script it shares.
	 *
	 * All four hex-web fronts declare the identical `"prebuild":
	 * "../../common/copy-assets.sh"`, so editing that shell script would run the docs
	 * guard for three sites that have no docs. The append is inside the string literal in
	 * the original bytes, which is what preserves the tabs and the key order that
	 * `JSON.stringify` would not.
	 */
	prebuildHook(text: string | null, site: SiteDescriptor): string | null {
		if (text === null) return null;
		const block = soleBlock(text, 'scripts');
		if (block === null || block.kind !== 'object') return null;
		const fragment = prebuildFragment(site);

		const region = text.slice(block.open, block.close + 1);
		const key = /"prebuild"\s*:\s*"/.exec(region);
		if (key?.index !== undefined) {
			let cursor = block.open + key.index + key[0].length;
			while (cursor < text.length) {
				if (text[cursor] === '\\') {
					cursor += 2;
					continue;
				}
				if (text[cursor] === '"') break;
				cursor += 1;
			}
			if (cursor >= text.length) return null;
			return `${text.slice(0, cursor)} && ${fragment}${text.slice(cursor)}`;
		}
		return insertIntoBlock(text, block, [`"prebuild": ${JSON.stringify(fragment)}`]);
	},

	docsLib(text: string | null): string | null {
		// Created, never rewritten. A file that exists and does not derive is a file
		// somebody wrote, and this module's own header invites that.
		if (text !== null) return null;
		return docsLibModule();
	},

	checkDocsShim(_text: string | null, site: SiteDescriptor): string | null {
		return checkDocsShim(site);
	},

	/**
	 * An insertion, not a round trip.
	 *
	 * A parse and re-serialise was tried and rejected on the output: `JSON.stringify`
	 * puts every array element on its own line, so adding one server reformatted all
	 * three of hex-web's, and the diff of a one-commit file that nobody had touched since
	 * March would have been every line in it. The edit belongs to this package; the rest
	 * of the file belongs to whoever wrote it.
	 */
	mcpJson(text: string | null, site: SiteDescriptor): string | null {
		const entry = mcpServerEntry(site);
		if (text === null) {
			const indent = '\t';
			return (
				'{\n' +
				`${indent}"mcpServers": {\n` +
				`${indent}${indent}"hexdocs": {\n` +
				`${indent}${indent}${indent}"command": ${JSON.stringify(entry.command)},\n` +
				`${indent}${indent}${indent}"args": []\n` +
				`${indent}${indent}}\n` +
				`${indent}}\n` +
				'}\n'
			);
		}
		const block = soleBlock(text, 'mcpServers');
		if (block === null || block.kind !== 'object') return null;
		// A `hexdocs` entry that is present with a different command is somebody's own
		// wiring, and a second key of the same name would be a file that parses to
		// whichever one came last.
		if (/"hexdocs"\s*:/.test(text.slice(block.open, block.close + 1))) return null;
		const indent = entryIndent(text, block);
		const unit = detectIndent(text);
		return insertIntoBlock(text, block, [
			`"hexdocs": {\n${indent}${unit}"command": ${JSON.stringify(entry.command)},\n` +
				`${indent}${unit}"args": []\n${indent}}`,
		]);
	},

	gitignore(text: string | null): string | null {
		const existing = text === null ? '' : withTrailingNewline(text);
		const lines = existing.split('\n').map((line) => line.trim());
		const missing = GITIGNORE_ENTRIES.filter((entry) => !lines.includes(entry));
		if (missing.length === 0) return existing;
		const header = '# Written by `hexdocs install`. Prefetched bundles are build output.';
		return `${existing}${existing === '' ? '' : '\n'}${header}\n${missing.join('\n')}\n`;
	},

	refuse(): string | null {
		return null;
	},
} as const;

