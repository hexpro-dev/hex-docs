			// the stanza alone produces a declared submodule with no gitlink, which is a
			// state the check then has to report and which a fresh clone gets nothing
			// from. `git submodule add` writes the stanza, stages the gitlink and creates
			// the checkout in one operation, and it refuses if the path is already in the
			// index, so an append here would also make that command fail.
