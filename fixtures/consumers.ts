/**
 * Two consuming websites, as bytes, materialised into a temporary directory.
 *
 * **Why these are strings in a TypeScript file rather than files on disk.** Every design
 * that proposed step 5 committed `fixtures/consumer/apps/front/app/routes.ts` and its
 * siblings as real files, and all of them break this repository's own ladder on day one.
 * Measured, not predicted:
 *
 *   * `tsconfig.test.json` and `kit/tsconfig.json` both include `fixtures`, so a copied
 *     `routes.ts` importing `@react-router/dev/routes` and a `.tsx` sitemap route fail
 *     the typecheck row against a program that has neither the dependency nor a DOM lib.
 *   * `scripts/lint.mjs` has `fixtures` in `REQUIRED_DIRS` and scans `.ts`, `.tsx` and
 *     `.json`, and the real `tsconfig.json`, `routes.ts` and `root.tsx` each carry an em
 *     dash. A faithful copy fails the banned-character scan, and the only exemption
 *     mechanism is scoped to declared code points in `fixtures/planted.json`, which would
 *     then have to pin an em dash in a consumer fixture forever.
 *   * `pnpm format` rewrites `- "!common/docs"` to single quotes in a YAML file, and the
 *     double quotes are the whole point: the consumer's own guard matches that literal
 *     string including them.
 *
 * Held as strings, none of that applies: the content is opaque to Prettier, invisible to
 * the typechecker, and every non-ASCII character is written as an escape. It is also the
 * pattern `materialiseCorpus()` already established one directory over.
 *
 * **These are the real bytes of the files a code path reads**, taken from hex-web and
 * kcalc-web in September 2026, and not minimal shapes written for the checks. Step 5's
 * fixtures were minimal, and the minimal versions hid what step 8 had to fix: a routes file
 * without hex-web's tuple annotation selected the wrong instruction, a sitemap with a
 * `render()` helper hid the lastmod lookup a docs spread breaks on kcalc, a tsconfig setting
 * `resolveJsonModule` itself hid the `extends` chain both real consumers depend on, a deploy
 * config with no `sites` block made every test patch one in, and a hex-web with no `common/`
 * directory made every test pass the mount by hand. Where a file is cut down, its `why` says
 * what was cut and why nothing reads it: `root.tsx` is its imports and its `Layout` head, and
 * `deploy.config.json` is its `sites` projects and its `hash` block, because the rest of each
 * names hosts and settings a public repository has no reason to carry.
 */

